"""Write api/catalog/fno-screens.md, the F&O data catalog's plain-words field tables (story P1), from the contract's own
annotations, so the tables cannot drift from the schemas. One section per screen: its endpoint, page, freshness, empty
state, Mock examples by case, what is never sent, and per field its meaning, unit, backend record, freshness,
visibility and whether the backend can fill it today.

  python3 tools/api/render_fno_catalog.py           write the file
  python3 tools/api/render_fno_catalog.py --check   exit 1 if the file is not current"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bundle  # noqa: E402
from check_fno_screens import RECORDS, op_examples  # noqa: E402
from fno_walk import payload_name, screen_leaves, screen_operations  # noqa: E402

OUT = bundle.API / "catalog" / "fno-screens.md"
HEAD = """# F&O data catalog (story P1, generated)

Generated by `python3 tools/api/render_fno_catalog.py` from `api/schemas/fno-*.yaml`, `api/paths/fno-screens.yaml`
and `api/examples/fno-screens.json`; do not edit by hand. The owner (15 Oct 2026): mock data shared by the front end
and the back end, so both can build their parts apart and integrate later. Every example is **Mock** (made-up numbers
on future dates); every money figure is **Paper**; the card says **PAPER ONLY**. Checked by
`python3 tools/api/check_fno_screens.py` here and by the pinned copy's tests in exepex/trading.

How to read the columns:
- **Visibility**: `public` may appear in the public repositories; `owner` is for the owner's signed-in dashboard only
  and never enters a public repository (live card legs and entry ranges: card records are kept in Google Drive only,
  owner 15 Oct 2026). Strategy internals are not a column: they are never sent (each screen lists them).
- **Backend today**: `yes` names the backend record that holds the value today (`<record>:<field>`, records below);
  `no` names the story that builds it. A `no` field is never filled with a made-up value: until its story is built, the
  page is not published (each endpoint answers 501).

Backend records named in the tables (exepex/trading):

| Record | Where it is defined |
|---|---|
"""


def cell(text) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def screen_section(doc: dict, path: str, op: dict, leaves: list) -> list[str]:
    name = payload_name(doc, op)
    schema = doc["components"]["schemas"][name]
    lines = [f"## {op['summary']}", "", f"`GET {path}` · `{op['operationId']}` · {op['x-read-model']}", "",
             f"- **Freshness:** {op['x-freshness']}", f"- **Empty state:** {op['x-empty']}",
             f"- **What it holds:** {cell(schema.get('description'))}", "- **Mock examples:**"]
    for key, (example_name, example) in op_examples(doc, op).items():
        lines.append(f"  - `{key}` ({example['x-case']}): {cell(example['summary'])}. {cell(example.get('description'))}")
    lines.append("- **Never sent (strategy internals):** " + "; ".join(schema["x-never-sent"]))
    built = [leaf for leaf in leaves if leaf.fill == "built"]
    lines += [f"- **Fields:** {len(leaves)}, of which the backend can fill {len(built)} today", "",
              "| Field | Meaning | Unit | Source record (backend) | Freshness | Visibility | Backend today |",
              "|---|---|---|---|---|---|---|"]
    for leaf in leaves:
        today = f"yes (`{leaf.record}`)" if leaf.fill == "built" else f"no: {leaf.catalog.get('story')}"
        lines.append(f"| `{leaf.path.removeprefix('payload.')}` | {cell(leaf.description)} | {cell(leaf.unit)} | "
                     f"{cell(leaf.catalog.get('source'))} | {cell(leaf.catalog.get('freshness'))} | {leaf.visibility} | {today} |")
    return lines + [""]


def render(doc: dict) -> str:
    leaves = screen_leaves(doc)
    lines = HEAD.splitlines() + [f"| `{record}` | {where} |" for record, where in RECORDS.items()] + [""]
    for path, op in screen_operations(doc):
        lines += screen_section(doc, path, op, [leaf for leaf in leaves if leaf.op == op["operationId"]])
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = render(bundle.bundle())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        print(f"fno catalog: {OUT.relative_to(bundle.REPO)} is {'current' if current == text else 'NOT current (run tools/api/render_fno_catalog.py)'}")
        return 0 if current == text else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"fno catalog: wrote {OUT.relative_to(bundle.REPO)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
