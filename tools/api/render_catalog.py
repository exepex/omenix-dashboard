"""Render api/catalog/catalog.md, the data catalog of the block endpoints (story W10 criterion 4), from the contract
itself (x-catalog, x-unit, x-element on every field), so the catalog can never drift from the schemas.

  python3 tools/api/render_catalog.py          rewrite api/catalog/catalog.md
  python3 tools/api/render_catalog.py --check  exit 1 if it is out of date"""

from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bundle  # noqa: E402
from walk import block_fields, block_operations  # noqa: E402

OUT = bundle.API / "catalog/catalog.md"
PUBLISHER = {"stock": "stock tool", "fno": "exepex/trading", "dashboard": "dashboard"}
STATUS = {"published": "published", "planned": "not yet published"}


def published_today(leaves) -> str:
    """Whether a backend publishes the endpoint's payload today: every field, none, or some of them."""
    n, done = len(leaves), sum(1 for f in leaves if f.catalog.get("status") == "published")
    return "yes (only the block row is new)" if done == n else "**no: no backend publishes it**" if done == 0 else f"partly ({done} of {n} fields)"


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def element_label(e: dict) -> str:
    where = e["row"] if e["row"] else e["section"]
    return f"{e['notes'][:2]} · {where}"


ROLE = {"x-stored": "the whole table; the route pages it", "x-inputs": "an input the block's publisher reads"}


def stored_parts(doc: dict, ops) -> list[str]:
    """What publishers store where the route serves another shape (api/schemas/blocks-stored.yaml)."""
    lines = ["", "## Stored parts", "", "What publishers store where it differs from the served block: a whole table the route pages, or one",
             "publisher's input that another reads to build the block (checked by `tools/api/check_stored.py`).", "",
             "| Endpoint | Stored part | Role | Publisher | Read model | Story | Status |", "|---|---|---|---|---|---|---|"]
    for path, _, op in ops:
        for key, role in ROLE.items():
            for name in op.get(key, []):
                by = doc["components"]["schemas"][name]["x-stored-by"]
                lines.append(f"| `GET {path}` | `{name}` | {role} | {PUBLISHER[by['publisher']]} | {cell(by['read_model'])} | `{by['story']}` | {STATUS[by['status']]} |")
    return lines


def render() -> str:
    doc = bundle.bundle()
    elements = {e["id"]: e for e in yaml.safe_load((bundle.API / "catalog/elements.yaml").read_text(encoding="utf-8"))}
    stories = yaml.safe_load((bundle.API / "catalog/stories.yaml").read_text(encoding="utf-8"))
    fields = [f for f in block_fields(doc) if f.leaf]
    ops = list(block_operations(doc))
    lines = ["# Data catalog of the block endpoints (frame, Home, screener, Markets overview)", "",
             "Generated by `python3 tools/api/render_catalog.py` from the contract (`api/`); do not edit by hand. Conventions:",
             "`api/catalog/README.md`. Every money figure is Paper. Units: percent points (1.25 = +1.25 %), probabilities 0-1,",
             "instants in UTC (shown in IST or ET), money in the market's own currency (INR in India, USD in the US, never summed",
             "or converted). Status `published`: the publisher stores the value today (the named source); only the block row is",
             "new. Status `not yet published` (`x-status: planned` in the schemas): no backend publishes it yet; the story will.", "",
             "## Endpoints", "", "One endpoint per independent screen block; where one record feeds several blocks, the last column says why.", "",
             "| Endpoint | Publisher | Published today? | Feeds | Read model | Freshness | Cache | Empty state | Shared because |", "|---|---|---|---|---|---|---|---|---|"]
    for path, _, op in ops:
        feeds = ", ".join(f"`{e}`" for e in op["x-feeds"])
        mine = [f for f in fields if f.op == op["operationId"] and f.path.startswith("payload")]
        lines.append(f"| `GET {path}` | {PUBLISHER[op['x-publisher']]} | {published_today(mine)} | {feeds} | {cell(op['x-read-model'])} | {cell(op['x-freshness'])} | "
                     f"{cell(op['x-cache'])} | {cell(op['x-empty'])} | {cell(op.get('x-shared', ''))} |")
    lines += stored_parts(doc, ops)
    lines += ["", "## Elements (the notes.md contracts) and the endpoints that feed them", "", "| Element | Notes row | Endpoints |", "|---|---|---|"]
    served = defaultdict(set)
    for f in fields:
        if f.path.startswith("payload"):
            for e in f.elements:
                served[e].add(f.op)
    path_of = {op["operationId"]: path for path, _, op in ops}
    for eid, e in elements.items():
        target = e.get("static") and f"none: {e['static']}" or ", ".join(f"`{path_of[o]}`" for o in sorted(served[eid]))
        lines.append(f"| `{eid}` | {cell(element_label(e))} | {cell(target)} |")
    planned = Counter(f.catalog["story"] for f in fields if f.catalog.get("status") == "planned")
    lines += ["", "## Stories", "", "| Story | Exists | Fields not yet published | What it covers |", "|---|---|---|---|"]
    for sid, s in stories.items():
        lines.append(f"| `{sid}` | {'yes' if s['exists'] else '**no: to be written**'} | {planned.get(sid, 0)} | {cell(s.get('scope') or s['title'])} |")
    lines += ["", "## Open questions (owner)", "",
              "- Should the stock tool publish a year of daily FII/DII flows (5 days today: 1D and 1W totals only)?",
              "- Events: 34's data has no `major` flag; it is derived from the regime record's `major_event_names` until published.",
              "", "## Fields", ""]
    for path, _, op in ops:
        lines += [f"### `GET {path}` ({op['operationId']})", "", "| Field | Elements | Publisher | Source | Unit | Freshness | Story | Status |",
                  "|---|---|---|---|---|---|---|---|"]
        for f in fields:
            if f.op == op["operationId"]:
                c = f.catalog
                lines.append(f"| `{f.path}` | {', '.join(f.elements)} | {PUBLISHER.get(c.get('publisher'), c.get('publisher'))} | {cell(c.get('source'))} | "
                             f"{cell(f.unit)} | {cell(c.get('freshness'))} | `{c.get('story')}` | {STATUS.get(c.get('status'), c.get('status'))} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("catalog: api/catalog/catalog.md is current" if same else "catalog: api/catalog/catalog.md is out of date (run tools/api/render_catalog.py)")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"catalog: wrote {OUT.relative_to(bundle.REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
