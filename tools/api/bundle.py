"""The app API contract as one OpenAPI 3.1 document (api/README.md "Layout").

  api/openapi.yaml         info, servers, security, tags, the shared parameters, headers, responses and schemas
  api/paths/<page>.yaml    a map of path -> path item
  api/schemas/<page>.yaml  a map of schema name -> schema
  api/examples/<name>.json a map of example name -> OpenAPI Example object (generated by tools/api/examples.py)

`bundle()` merges them into one document: paths join `paths`, schemas join `components.schemas`, examples join
`components.examples`; a name defined twice is an error. Every `$ref` is written against the bundled document, so the
bundle has local refs only. `python3 tools/api/bundle.py > openapi.json` prints it (same merge rule as the stock
repository's scripts/marketbrief/warehouse/openapi_spec.py, plus the examples folder)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
API = REPO / "api"


class SpecError(ValueError):
    """The contract files do not merge into one document."""


def load_yaml(path: Path) -> dict:
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise SpecError(f"api contract: {path.name} must be a mapping")
    return data


def merge(target: dict, extra: dict, kind: str, where: str) -> None:
    for name, value in extra.items():
        if name in target:
            raise SpecError(f"api contract: {kind} {name!r} is defined twice ({where})")
        target[name] = value


def bundle(folder: Path = API) -> dict:
    document = load_yaml(folder / "openapi.yaml")
    document.setdefault("paths", {})
    components = document.setdefault("components", {})
    schemas = components.setdefault("schemas", {})
    examples = components.setdefault("examples", {})
    for path in sorted((folder / "paths").glob("*.yaml")):
        merge(document["paths"], load_yaml(path), "path", f"paths/{path.name}")
    for path in sorted((folder / "schemas").glob("*.yaml")):
        merge(schemas, load_yaml(path), "schema", f"schemas/{path.name}")
    for path in sorted((folder / "examples").glob("*.json")):
        merge(examples, json.loads(path.read_text(encoding="utf-8")), "example", f"examples/{path.name}")
    return document


def schema_files(folder: Path = API) -> dict[str, str]:
    """Schema name -> the file that defines it (for reports)."""
    return {name: path.name for path in sorted((folder / "schemas").glob("*.yaml")) for name in load_yaml(path)}


if __name__ == "__main__":
    json.dump(bundle(), sys.stdout, indent=1, ensure_ascii=False)
    sys.stdout.write("\n")
