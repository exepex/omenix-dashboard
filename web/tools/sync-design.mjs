// Copies the design system (design/system/ and design/mockups/_shared/shell.css) into the app, unchanged:
//   web/styles/tokens.css, tokens-dark.css, components.css, page.css  <- tokens.css, tokens-dark.css, components.css,
//                                                                        _shared/shell.css
//   web/components/icons/sprite.generated.ts        <- icons.svg as a string constant (inlined once in the root layout)
//   web/lib/shell/fixture/shell.generated.json      <- mockups/30-shell/data.json (the app frame's fixture adapter, W8)
//   web/lib/home/fixture/blocks.generated.json      <- api/examples/blocks.json (Home's block examples, W9: the W10
//                                                     contract's examples, taken from 30-shell and 31-dashboard)
// Run from web/: `node tools/sync-design.mjs`; `--check` exits 1 when a copy is out of date (lib/ui/tests/design-sync.test.ts).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const design = join(web, "..", "design");

export function expectedCopies() {
  const read = (p) => readFileSync(join(design, p), "utf8");
  const sprite = read("system/icons.svg");
  return {
    "styles/tokens.css": read("system/tokens.css"),
    "styles/tokens-dark.css": read("system/tokens-dark.css"),
    "styles/components.css": read("system/components.css"),
    "styles/page.css": read("mockups/_shared/shell.css"),
    "components/icons/sprite.generated.ts":
      "// Generated by web/tools/sync-design.mjs from design/system/icons.svg (Material Symbols Outlined, Apache 2.0,\n" +
      "// design/system/LICENSE-material-symbols.txt). Do not edit; run `node tools/sync-design.mjs`.\n" +
      `export const ICON_SPRITE = ${JSON.stringify(sprite)};\n`,
    "lib/shell/fixture/shell.generated.json": read("mockups/30-shell/data.json"),
    "lib/home/fixture/blocks.generated.json": readFileSync(join(design, "..", "api", "examples", "blocks.json"), "utf8"),
  };
}

export function staleCopies() {
  return Object.entries(expectedCopies())
    .filter(([path, text]) => !existsSync(join(web, path)) || readFileSync(join(web, path), "utf8") !== text)
    .map(([path]) => path);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = staleCopies();
    if (stale.length) { console.error("out of date: " + stale.join(", ")); process.exit(1); }
    console.log("design copies current");
  } else {
    for (const [path, text] of Object.entries(expectedCopies())) writeFileSync(join(web, path), text);
    console.log("design copies written");
  }
}
